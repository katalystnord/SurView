// What SurView measures on images it did not make, against an answer it did not
// write.
//
// WHY THIS EXISTS. Every other accuracy case in this suite measures our own
// synthetic examples against the answer our own generator states. That is sound
// verification of the IMPLEMENTATION -- it says the code computes what we
// intended -- and it says nothing whatever about whether what we intended
// agrees with the field. Until 2026-09-14 nothing in this project had ever
// checked SurView against anything but itself, and the ROADMAP called that the
// largest single gap in its evidence.
//
// The images here are the iDICs/SEM DIC Challenge 1.0 Sample 3 set: a speckle
// reference and eleven targets rigidly shifted by 0.00 to 1.00 px in steps of
// 0.10, generated by somebody else, by a method that is not ours, with the
// prescribed shift stated in each file's own NAME.
//
// ⚑ THE ANSWER HERE IS PRESCRIBED, NOT EXACT BY CONSTRUCTION, and the
// difference matters. Our synthetic sets render each frame afresh from an
// analytic pattern, so no pixel is ever resampled and the stated answer IS the
// truth. This set was made by shifting one photograph in the Fourier domain and
// adding about two grey levels of noise, so the image carries whatever that
// resampling and that noise do. A disagreement here is therefore evidence about
// the pair of us, not proof about us alone -- which is exactly what makes it
// worth having, and exactly why the tolerance below is not the tolerance the
// synthetic cases use.
//
// ⚑ THE DATA IS NOT IN THIS REPOSITORY AND MUST NOT BE. The challenge sets
// state no licence or terms of use; they may be used, and whether they may be
// redistributed is unestablished (see the MANIFEST beside the download). So
// these cases read the set from wherever it was unpacked, named by
// SURVIEW_DIC_CHALLENGE_SAMPLE3, and SKIP when it is not there. A fresh clone
// and CI run the parser cases below and skip the measurement, which is the
// honest arrangement rather than a silently absent check: the run says
// "skipped", not "passed".
//
// NEGATIVE CHECK (2026-09-14), each reverted after:
//   - the stated shift read as x for both components: the lopsided-name case
//     went red, the measurement case did NOT (see the limitation below).
//   - the sign of the parsed shift flipped: both parser cases and the
//     measurement went red.
//   - a name with no X token read as a shift of zero instead of refusing:
//     `a_name_that_states_no_shift_is_not_a_shift_of_zero` went red.
//   - the guard refusing an unstated answer removed: a field measuring no
//     movement then agreed perfectly with an answer nobody gave, and
//     `a_measurement_set_against_no_stated_answer_agrees_with_nothing` went red.
//   - the tolerance widened to 0.1 px: the measurement stayed green, which is
//     why the tolerance is argued from the bias below rather than chosen to
//     fit.
//   - the name read with QFileInfo::baseName instead of completeBaseName: four
//     of the reading cases went red, because baseName stops at the first dot
//     and that dot is inside the shift itself.
//
// ⚑ WHAT THIS DOES NOT CATCH, stated because it looks like coverage and is
// not: every frame in Sample 3 shifts EQUALLY in x and y, so the measurement
// case cannot tell u from v, and a build that reported u for both components
// would pass it. That is the fixture-agrees-with-itself trap this project has
// earned four times over. The parser half is closed by a lopsided name below;
// the measurement half wants Sample 14, whose displacement is in x alone, and
// SurView cannot open Sample 14 today (its reference and targets differ by one
// pixel in width and the run refuses them). Recorded in the ROADMAP.

#include "core/Correlation.h"
#include "core/DicChallenge.h"
#include "core/Roi.h"

#include <QDir>
#include <QTest>

#include <cmath>

namespace
{

// Coarse on purpose, and first order on purpose. A rigid shift is exactly what
// a first-order shape function describes, so this case measures whether the
// answer is right rather than how hard the solver can be made to work.
CorrelationSettings settings()
{
    CorrelationSettings s;
    s.solver = CorrelationSettings::ICGN;
    s.shapeOrder = 1;
    s.subsetRadius = 16;
    s.gridStep = 16;
    s.maxIterations = 15;
    s.convergence = 0.001;
    s.strainEnabled = false;
    return s;
}

CorrelationResult measure(const QString &reference, const QString &target)
{
    CorrelationRunner runner(settings(), RegionOfInterest(), reference, target);
    CorrelationResult result;
    QString failure;
    QObject::connect(&runner, &CorrelationRunner::finished,
                     [&result](const CorrelationResult &r) { result = r; });
    QObject::connect(&runner, &CorrelationRunner::failed,
                     [&failure](const QString &reason) { failure = reason; });
    runner.run();
    if (!failure.isEmpty())
        qWarning("correlation failed: %s", qPrintable(failure));
    return result;
}

QString sampleDirectory()
{
    return qEnvironmentVariable("SURVIEW_DIC_CHALLENGE_SAMPLE3");
}

}  // namespace

