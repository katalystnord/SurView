    void a_name_that_states_no_shift_is_not_a_shift_of_zero();
    void a_name_stating_only_one_axis_states_no_shift();
    void a_stated_shift_of_zero_is_a_statement_not_an_absence();
    void the_other_numbers_in_a_challenge_name_are_not_the_shift();

    void the_agreement_reports_each_axis_against_its_own_stated_value();
    void an_unconverged_point_is_left_out_of_the_agreement();
    void an_agreement_over_no_points_is_refused_not_reported_as_exact();
    void a_measurement_set_against_no_stated_answer_agrees_with_nothing();

